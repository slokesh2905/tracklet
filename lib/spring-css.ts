import { stepSpring, type SpringParams } from "./spring";

/**
 * The app's CSS springs. Every transition and enter/exit animation uses one of these instead
 * of a hand-picked ease and duration. All are critically damped (damping 1.0): nothing in the
 * stylesheet was thrown by a gesture, so nothing overshoots. Motion that a gesture did throw
 * (releasing a sheet) is driven by the JS spring in use-sheet-motion.ts, which can bounce.
 *
 *   press  response 0.1   the instant a button/link/card is touched
 *   fast   response 0.2   colour, opacity, small state changes, press release (the default)
 *   base   response 0.4   things that move: menus, dialogs, sheets, the page pushing back
 */
export const SPRINGS = {
  press: { damping: 1, response: 0.1 },
  fast: { damping: 1, response: 0.2 },
  base: { damping: 1, response: 0.4 },
} as const satisfies Record<string, SpringParams>;

export type SpringName = keyof typeof SPRINGS;

const round = (n: number) => Number(n.toFixed(4));

/**
 * Sample a spring going 0 -> 1 from rest into a CSS `linear()` easing. Its duration is the
 * spring's own settle time (within 0.2% and effectively stopped), not a number we chose.
 */
export function springToCss(params: SpringParams) {
  const state = { x: 0, v: 0 };
  let t = 0;
  while (t < 5) {
    stepSpring(state, 1, 0.001, params);
    t += 0.001;
    if (Math.abs(1 - state.x) < 0.002 && Math.abs(state.v) < 0.02) break;
  }
  const durationMs = Math.ceil(t * 1000);
  const steps = Math.max(8, Math.round(durationMs / 8));

  const points: number[] = [];
  for (let i = 1; i < steps; i++) {
    const s = { x: 0, v: 0 };
    stepSpring(s, 1, ((i / steps) * durationMs) / 1000, params);
    points.push(round(s.x));
  }
  return { easing: `linear(0, ${points.join(", ")}, 1)`, durationMs };
}

/**
 * A CSS time ("308ms", ".308s") in milliseconds. Read spring durations through this: the CSS
 * minifier rewrites `565ms` as `.565s`, so a bare parseFloat is off by a factor of 1000.
 */
export function cssTimeToMs(value: string) {
  const v = value.trim();
  return v.endsWith("ms") ? parseFloat(v) : parseFloat(v) * 1000;
}

/** The contents of app/springs.css. */
export function springsCss() {
  const lines = ["/* Generated by scripts/gen-springs.mts from lib/spring-css.ts. Do not edit by hand. */", ":root {"];
  for (const [name, params] of Object.entries(SPRINGS)) {
    const { easing, durationMs } = springToCss(params);
    lines.push(`  /* damping ${params.damping}, response ${params.response}s */`);
    lines.push(`  --spring-${name}: ${easing};`);
    lines.push(`  --spring-${name}-duration: ${durationMs}ms;`);
  }
  lines.push("}", "");
  return lines.join("\n");
}
